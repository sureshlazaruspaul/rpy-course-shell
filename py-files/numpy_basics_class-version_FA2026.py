import numpy as np # type: ignore
from icecream import ic # type: ignore

"""*Things to remember:*
1. Numpy arrays allow for efficient mathematical operations on
    entire arrays without the need for explicit loops.
2. Element-wise operations can be performed using standard operators (+, -, *, /) or numpy functions (np.add, np.subtract, np.multiply, np.divide).
3. Icecream library provides a convenient way to print variables.

*Syntax to remember:*
**np.array**, **np.add**, **np.subtract**, **np.multiply**, **np.divide**, **np.zeros_like**, **np.concatenate**

*Objective:*
Calculate GROSS PROFIT, GROSS MARGIN, DEBT-EQUITY RATIO, and BALANCE SHEET EQUATION from financial data using numpy arrays.

Input a vector (list) of financial data from yahoo finance

NOTE:
-   a list is a collection of items separated by commas.
-   a numeric list is a collection of numbers separated by commas.
-   numpy calculations require a numeric list

**AAPL Income Statement (in thousands)**
"""

sales = [391035000, 383285000, 394328000, 365817000] # standard list of sales data for four years

ic(sales)

print(sales)

cogs = [210352000, 214137000, 223546000, 212981000] # standard list of cost of goods sold data for four years

ic(cogs)

"""**AAPL Balance Sheet (in thousands)**"""

total_assets = [364980000, 352583000, 352755000, 351002000] # standard list of total assets data for four years
total_liabilities = [308030000, 290437000, 302083000, 287912000] # standard list of total liabilities data for four years
total_equity = [56950000, 62146000, 50672000, 63090000] # standard list of total equity data for four years

"""*convert all lists to np.array*"""

sales_arr = np.array(sales) # a numeric array of sales data for four years

ic(sales_arr)

cogs_arr = np.array(cogs) # a numeric array of cost of goods sold data for four years

ic(cogs_arr)

total_assets_arr = np.array(total_assets) # a numeric array of total assets data for four years

ic(total_assets_arr)

total_liabilities_arr: np.ndarray = np.array(total_liabilities) # a numeric array of total liabilities data for four years

ic(total_liabilities_arr)

total_equity_arr = np.array(total_equity) # a numeric array of total equity data for four years

ic(total_equity_arr)

"""**WHAT IS GROSS PROFIT?**

(i) traditional way
"""

gross_profit_arr = sales_arr - cogs_arr

ic(gross_profit_arr)

"""(ii) numpy function: np.subtract()"""

gross_profit1_arr = np.subtract(sales_arr, cogs_arr)

ic(gross_profit1_arr)

"""**print: different methods**

(a) calculate inside a print statement
"""

print("Gross Profit (in thousands):", gross_profit_arr) # print as an array

print("Gross Profit (in millions):", gross_profit_arr/1000) # print as an array

print("Gross Profit (in billions):", gross_profit_arr/(10**6)) # print as an array

print("Gross Profit (in trillions):", gross_profit_arr/(10**9)) # print as an array

"""*print using f-string*"""

print(f"f-string output: {gross_profit_arr=}")

"""*print using icecream*"""

ic(gross_profit_arr)

"""Balance Sheet Identity: Assets = Equity + Liabilities
*check if left side equals right side in a balance sheet*
"""

balance_check = total_assets_arr - (total_liabilities_arr + total_equity_arr)

ic(balance_check)

"""nested numpy functions: np.subtract(), np.add()"""

balance_check_v2 = np.subtract(
    total_assets_arr,
    np.add(total_liabilities_arr, total_equity_arr)
)

ic(balance_check_v2)

"""*WHAT IS MARGINS? GROSS_PROFIT_MARGIN, EBIT_MARGIN, EBITDA_MARGIN*"""

gross_profit_margin_arr = gross_profit1_arr / sales_arr

ic(gross_profit1_arr, sales_arr, gross_profit_margin_arr)

"""fetching data for EBIT and EBITDA"""

ebit = [123216000, 114301000, 119437000, 111852000]
ebitda =[134661000, 125820000, 130541000, 123136000]

"""*Convert to np.array*"""

ebit_arr = np.array(ebit)
ebitda_arr = np.array(ebitda)

"""compute EBIT Margin using numpy function: np.divide()"""

ebit_margin_arr = np.divide(ebit_arr, sales_arr)

ic(ebit_margin_arr)

check_ebit_margin = ebit_margin_arr -(ebit_arr / sales_arr)

ic(check_ebit_margin) # must all be ZEROes

"""Compute EBITDA Margin using numpy function: np.divide()"""

ebitda_margin_arr = np.divide(ebitda_arr, sales_arr)

ic(ebitda_margin_arr)

"""compute Debt-Equity Ratio

(i) traditional way
"""

debt_equity_ratio_arr = total_liabilities_arr / total_equity_arr

ic(debt_equity_ratio_arr)

"""- using numpy function: np.divide()"""

debt_equity_ratio_arr_v2 = np.divide(total_liabilities_arr, total_equity_arr)

ic(debt_equity_ratio_arr_v2)

"""check D/E"""

check_de = debt_equity_ratio_arr - debt_equity_ratio_arr_v2

ic(check_de)

"""check step using numpy function: np.multiply()"""

ic(
    np.multiply(debt_equity_ratio_arr_v2, total_equity_arr) - total_liabilities_arr
)

"""**compute growth rates - year-over-year percentage change**

*sales growth rate*

use this to find lag
~ if sales numbers are arranged from
  recent year (2024) to oldest year (2021)

*background steps*

(a) slice an array
"""

sales_arr[1:]

"""(b) missing *NA* value"""

[np.nan]

"""(c) concatenate both (a) and (b) in a single numeric list"""

[sales_arr[1:], [np.nan]]

"""(d) now, put it altogether as a numpy array using the function: np.concatenate()"""

lag_sales_arr = np.concatenate([sales_arr[1:], [np.nan]])

ic(sales_arr, lag_sales_arr)

"""use this to find lag
~ if sales numbers are arranged from
  oldest year (2021) to recent year (2024)
"""

sales_growth_arr = np.subtract(np.divide(sales_arr, lag_sales_arr), 1)

ic(sales_growth_arr)

"""*EBITDA growth rate*

use this to find lag
~ if EBITDA numbers are arranged from
  recent year (2024) to oldest year (2021)
"""

lag_ebitda_arr = np.concatenate([ebitda_arr[1:], [np.nan]])

ic(ebitda_arr, lag_ebitda_arr)

ebitda_growth_arr = np.divide(ebitda_arr, lag_ebitda_arr) - 1

ic(ebitda_growth_arr)

"""EBIT growth rate

use this to find lag
~ if EBIT numbers are arranged from
  recent year (2024) to oldest year (2021)
"""

lag_ebit_arr = np.concatenate([ebit_arr[1:], [np.nan]])

ic(ebit_arr, lag_ebit_arr)

"""use this to find lag
~ if EBIT numbers are arranged from
  oldest year (2021) to recent year (2024)
"""

ebit_growth_arr = np.divide(ebit_arr, lag_ebit_arr) - 1
ic(ebit_growth_arr)